// Draws an illustration for every sample piece from its category, material, finish and color.
// Run: node scripts/make-sample-images.mjs   (needs playwright; writes assets/images/samples/*.png
// and src/content/sample-images.ts). The drawings are original, so there are no photo rights to worry about.
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');

const src = readFileSync('src/content/sample-gear.ts', 'utf8');
const rows = [];
let cat = null;
for (const line of src.split('\n')) {
  const m = /make\('([^']+)'/.exec(line);
  if (m) cat = m[1];
  const r = /^\s*\['([^']+)', '([^']*)', '([^']*)', (null|'[^']*'), (null|'[^']*'), '(#[0-9A-Fa-f]{6})', (null|\d+)\],/.exec(line);
  if (r && cat) rows.push({ category: cat, name: r[1], material: r[4] === 'null' ? null : r[4].slice(1, -1), finish: r[5] === 'null' ? null : r[5].slice(1, -1), color: r[6] });
}
export const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

import { svg } from './item-art.mjs';

mkdirSync('assets/images/samples', { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 320, height: 320 }, deviceScaleFactor: 1 });
const seen = new Set();
for (const it of rows) {
  const id = slug(it.name);
  if (seen.has(id)) throw new Error('Duplicate slug ' + id);
  seen.add(id);
  await page.setContent(`<body style="margin:0">${svg(it)}</body>`);
  await page.screenshot({ path: `assets/images/samples/${id}.jpg`, type: 'jpeg', quality: 86 });
}
await browser.close();
writeFileSync(
  'src/content/sample-images.ts',
  `/** Generated by scripts/make-sample-images.mjs. Drawings of the sample gear, bundled with the app. */\nimport type { ImageSourcePropType } from 'react-native';\n\nconst IMAGES: Record<string, ImageSourcePropType> = {\n${[...seen].map((id) => `  '${id}': require('../../assets/images/samples/${id}.jpg'),`).join('\n')}\n};\n\n/** The bundled drawing for a stored value like "sample:spyderco-para-3", or null. */\nexport function sampleImage(stored: string | null | undefined): ImageSourcePropType | null {\n  if (!stored?.startsWith('sample:')) return null;\n  return IMAGES[stored.slice(7)] ?? null;\n}\n`,
);
console.log('drew', rows.length);
