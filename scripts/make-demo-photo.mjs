// Builds the photo-identify demo: one picture with three items on a desk, plus each item's
// traced outline and canned answer. Writes assets/images/demo/demo-photo.jpg and
// src/content/demo-photo.ts. Run: node scripts/make-demo-photo.mjs (needs playwright, python3 with opencv).
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { svg } from './item-art.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');

const W = 1200;
const H = 900;

// Where each drawing sits (its 320x320 square, scaled) and how it's turned.
const ITEMS = [
  { art: { category: 'Flashlight', material: 'Aluminum', finish: 'Anodized', color: '#2B2E33' }, x: 40, y: 20, size: 640, turn: -4,
    answer: { category: 'Flashlight', brand: 'Olight', model: 'Baton 3 Pro Max', confidence: 'high', materials: ['Aluminum', 'Titanium'], finish: 'Anodized', color: '#2B2E33', notes: 'Black anodized aluminum body with a pocket clip and a knurled grip.' } },
  { art: { category: 'Knife', material: 'G10', finish: 'Stonewashed', color: '#2F5D50' }, x: 520, y: 120, size: 640, turn: 8,
    answer: { category: 'Knife', brand: 'Civivi', model: 'Elementum', confidence: 'medium', materials: ['G10', 'Micarta'], finish: 'Stonewashed', color: '#2F5D50', notes: 'Green textured handle with a drop-point blade and a pocket clip.' } },
  { art: { category: 'Pen', material: 'Zirconium', finish: 'Satin', color: '#1B1C1E' }, x: 150, y: 400, size: 640, turn: -2,
    answer: { category: 'Pen', brand: 'Tactile Turn', model: 'Mover', confidence: 'medium', materials: ['Zirconium', 'Aluminum', 'Titanium'], finish: 'Satin', color: '#1B1C1E', notes: 'Slim dark pen with a clip and a removable tail cap.' } },
];

const rename = (s, k) => s.replace(/id="([^"]+)"/g, `id="${k}-$1"`).replace(/url\(#([^)]+)\)/g, `url(#${k}-$1)`);
const drawing = (it, k) => {
  const inner = svg(it.art)
    .replace(/<rect width="320" height="320" fill="url\(#bg\)"\/>/, '') // no tile background
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '');
  return `<g transform="translate(${it.x} ${it.y}) rotate(${it.turn} ${it.size / 2} ${it.size / 2}) scale(${it.size / 320})">${rename(inner, k)}</g>`;
};

const desk = `
<defs>
 <linearGradient id="deskBase" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#8A5A34"/><stop offset=".5" stop-color="#9C6B40"/><stop offset="1" stop-color="#7A4D2C"/></linearGradient>
 <filter id="deskGrain"><feTurbulence type="fractalNoise" baseFrequency=".004 .12" numOctaves="4" seed="9"/><feColorMatrix values="0 0 0 0 .25  0 0 0 0 .13  0 0 0 0 .05  0 0 0 1.3 -.45"/></filter>
 <radialGradient id="vignette" cx=".5" cy=".5" r=".75"><stop offset=".55" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity=".45"/></radialGradient>
</defs>
<rect width="${W}" height="${H}" fill="url(#deskBase)"/>
<rect width="${W}" height="${H}" filter="url(#deskGrain)" opacity=".7"/>
<rect width="${W}" height="${H}" fill="url(#vignette)"/>`;

const scene = (only) => `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">${only === undefined ? desk : ''}${ITEMS.map((it, i) => (only === undefined || only === i ? drawing(it, `i${i}`) : '')).join('')}</svg>`;

mkdirSync('assets/images/demo', { recursive: true });
mkdirSync('scripts/.demo', { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
await page.setContent(`<body style="margin:0">${scene()}</body>`);
await page.screenshot({ path: 'assets/images/demo/demo-photo.jpg', type: 'jpeg', quality: 88 });

const found = [];
for (let i = 0; i < ITEMS.length; i += 1) {
  await page.setContent(`<body style="margin:0;background:transparent">${scene(i)}</body>`);
  await page.screenshot({ path: `scripts/.demo/mask-${i}.png`, omitBackground: true });
  found.push(JSON.parse(execFileSync('python3', ['scripts/trace_outline.py', `scripts/.demo/mask-${i}.png`], { encoding: 'utf8' })));
}
await browser.close();

const items = ITEMS.map((it, i) => ({
  category: it.answer.category,
  brand: it.answer.brand,
  brandRead: it.answer.brand,
  brandCandidates: [],
  model: it.answer.model,
  confidence: it.answer.confidence,
  material: it.answer.materials[0],
  materialOptions: it.answer.materials,
  finish: it.answer.finish,
  color: it.answer.color,
  notes: it.answer.notes,
  box: found[i].box,
  outline: found[i].outline,
}));
writeFileSync(
  'src/content/demo-photo.ts',
  `/**
 * The photo-identify demo: a picture of three items with each one's outline and a ready-made answer,
 * so the multi-item flow can be tried (and reviewed) with no camera and no AI request.
 * Generated by scripts/make-demo-photo.mjs.
 */
import type { Identified } from '@/lib/api';

export const DEMO_PHOTO = require('../../assets/images/demo/demo-photo.jpg');
export const DEMO_SIZE = { width: ${W}, height: ${H} };
export const DEMO_ITEMS: Identified[] = ${JSON.stringify(items, null, 2)};
`,
);
console.log('demo ok', found.map((f) => f.outline.length));
